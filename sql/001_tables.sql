-- Domain tables and their rules.
--
-- Django creates its own tables (app_user, sessions, admin log); everything below is owned by SQL.
-- Every rule is a named constraint, so it holds for every client: the web app, Django admin or psql.
-- The app maps constraint names to friendly form errors (see app/forms.py).

-- True if the text is a valid PostgreSQL regular expression. Used by a CHECK constraint.
CREATE FUNCTION is_valid_regex(p_pattern text) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    PERFORM '' ~ p_pattern;
    RETURN true;
EXCEPTION WHEN invalid_regular_expression THEN
    RETURN false;
END $$;

-- True if the text is an ISO date (YYYY-MM-DD) that exists in the calendar.
CREATE FUNCTION is_valid_date(p_value text) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF p_value !~ '^\d{4}-\d{2}-\d{2}$' THEN
        RETURN false;
    END IF;
    PERFORM p_value::date;
    RETURN true;
EXCEPTION WHEN datetime_field_overflow OR invalid_datetime_format THEN
    RETURN false;
END $$;


CREATE TABLE product (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT product_code_unique UNIQUE (code),
    CONSTRAINT product_name_unique UNIQUE (name),
    CONSTRAINT product_code_format CHECK (code ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(code) <= 50),
    CONSTRAINT product_name_not_blank CHECK (btrim(name) <> '' AND length(name) <= 100)
);

CREATE TABLE client (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    CONSTRAINT client_name_unique UNIQUE (name),
    CONSTRAINT client_name_not_blank CHECK (btrim(name) <> '' AND length(name) <= 100)
);

-- Per-product roles. Admins are users with app_user.is_superuser and need no membership.
CREATE TABLE membership (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    role       text NOT NULL DEFAULT 'editor',
    CONSTRAINT membership_unique UNIQUE (user_id, product_id),
    CONSTRAINT membership_role_valid CHECK (role IN ('manager', 'editor'))
);
CREATE INDEX membership_product_idx ON membership (product_id);

-- One allowed key in a product's configuration, with its type and limits.
CREATE TABLE schema_field (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    key        text NOT NULL,
    label      text NOT NULL,
    field_type text NOT NULL DEFAULT 'text',
    required   boolean NOT NULL DEFAULT true,
    min_value  numeric,
    max_value  numeric,
    choices    text[],
    pattern    text,
    help_text  text NOT NULL DEFAULT '',
    position   integer NOT NULL DEFAULT 0,
    CONSTRAINT schema_field_key_unique UNIQUE (product_id, key),
    CONSTRAINT schema_field_key_format CHECK (key ~ '^[a-z][a-z0-9_]*$' AND length(key) <= 50),
    CONSTRAINT schema_field_label_not_blank CHECK (btrim(label) <> '' AND length(label) <= 100),
    CONSTRAINT schema_field_type_valid CHECK (field_type IN ('text', 'integer', 'decimal', 'boolean', 'date', 'choice')),
    CONSTRAINT schema_field_range_only_numeric CHECK (field_type IN ('integer', 'decimal') OR (min_value IS NULL AND max_value IS NULL)),
    CONSTRAINT schema_field_min_le_max CHECK (min_value IS NULL OR max_value IS NULL OR min_value <= max_value),
    CONSTRAINT schema_field_choices_only_choice CHECK ((field_type = 'choice') = (choices IS NOT NULL)),
    CONSTRAINT schema_field_choices_at_least_two CHECK (choices IS NULL OR cardinality(choices) >= 2),
    CONSTRAINT schema_field_pattern_only_text CHECK (pattern IS NULL OR field_type = 'text'),
    CONSTRAINT schema_field_pattern_valid CHECK (pattern IS NULL OR is_valid_regex(pattern)),
    -- An unchecked box is a valid "No", so a Yes/No field can never be missing.
    CONSTRAINT schema_field_boolean_optional CHECK (field_type <> 'boolean' OR NOT required),
    CONSTRAINT schema_field_position_positive CHECK (position >= 0)
);

-- Current state of one product's configuration for one client.
-- data and version are maintained by triggers on config_version (see 002_versioning.sql).
CREATE TABLE configuration (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    bigint NOT NULL REFERENCES product (id) ON DELETE RESTRICT,
    client_id     bigint NOT NULL REFERENCES client (id) ON DELETE RESTRICT,
    status        text NOT NULL DEFAULT 'active',
    data          jsonb NOT NULL DEFAULT '{}',
    version       integer NOT NULL DEFAULT 0,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    updated_by_id bigint REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT configuration_product_client_unique UNIQUE (product_id, client_id),
    CONSTRAINT configuration_status_valid CHECK (status IN ('active', 'disabled')),
    CONSTRAINT configuration_data_is_object CHECK (jsonb_typeof(data) = 'object'),
    CONSTRAINT configuration_version_positive CHECK (version >= 0)
);

-- Immutable history: one row per saved change. This is the source of truth.
CREATE TABLE config_version (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    configuration_id bigint NOT NULL REFERENCES configuration (id) ON DELETE RESTRICT,
    number           integer NOT NULL,
    data             jsonb NOT NULL,
    comment          text NOT NULL,
    author_id        bigint REFERENCES app_user (id) ON DELETE RESTRICT,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT config_version_number_unique UNIQUE (configuration_id, number),
    CONSTRAINT config_version_number_positive CHECK (number >= 1),
    CONSTRAINT config_version_comment_not_blank CHECK (btrim(comment) <> '' AND length(comment) <= 200)
);
CREATE INDEX config_version_created_idx ON config_version (created_at DESC);
CREATE INDEX config_version_author_idx ON config_version (author_id);
